export const INTENTS: IntentDef[] = SPECS.map((s) => ({ id: s.id, label: s.label, kw: s.kw, tools: s.tools }));
export const LABELS: Record<string, string> = Object.fromEntries(SPECS.map((s) => [s.id, s.label]));
export const PER_INTENT = 24;

function fill(text: string, v: { a: string; b: string; n: string }): string {
  return text
    .replace(/\{a\}/g, v.a).replace(/\{b\}/g, v.b).replace(/\{n\}/g, v.n)
    .replace(/\bek (a|an|the) /gi, "ek ").replace(/\s{2,}/g, " ");
}

/** Steps are written for ANY request of this kind: they never carry the example's own numbers, places or targets. */
function generic(text: string): string {
  return text.replace(/\{a\}/g, "[the targets]").replace(/\{b\}/g, "[the place/topic]").replace(/\{n\}/g, "N").replace(/\bek (a|an|the) /gi, "ek ").replace(/\s{2,}/g, " ");
}

function expand(spec: Spec, count: number): Example[] {
  const N = spec.n ?? NUMS;
  const combos = new Map<string, { a: string; b: string; n: string; task: string }>();
  for (const t of spec.t) {
    const useB = t.includes("{b}"), useN = t.includes("{n}");
    for (const a of spec.a) for (const b of useB ? spec.b : [spec.b[0]]) for (const n of useN ? N : [N[0]]) {
      const v = { a, b, n };
      const task = fill(t, v);
      if (!combos.has(task)) combos.set(task, { ...v, task });
    }
  }
  // a fixed, well-mixed order (not "first N"), so every template and slot value shows up
  const list = [...combos.values()].sort((x, y) => (fnv(spec.id + x.task) < fnv(spec.id + y.task) ? -1 : 1)).slice(0, count);
  return list.map((v, i) => ({
    id: `seed-${spec.id}-${i + 1}`,
    intent: spec.id,
    task: v.task,
    title: spec.label,
    steps: spec.steps.map(generic),
    tools: spec.tools,
    pitfalls: spec.pitfalls.map(generic),
    verify: spec.verify.map(generic),
    source: "seed" as const,
    weight: 1,
    status: "live" as const,
    version: 1,
  }));
}

function fnv(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, "0");
}

let cache: Example[] | null = null;
/** All built-in examples (deterministic, same every time). */
export function seedExamples(): Example[] {
  if (!cache) cache = SPECS.flatMap((s) => expand(s, PER_INTENT));
  return cache;
}
